# Assemble split provider zips and point Terraform at build/tf-mirror (offline).
# Encoding: UTF-8 with BOM for Windows PowerShell 5.x
$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$MirrorRoot = Join-Path $ScriptDir "tf-mirror"

function Join-ZipParts {
    param([Parameter(Mandatory = $true)][string]$ZipPath)
    if (Test-Path $ZipPath) { return }
    $dir = Split-Path -Parent $ZipPath
    $name = Split-Path -Leaf $ZipPath
    $parts = @(Get-ChildItem -Path $dir -Filter ($name + ".part.*") -File | Sort-Object Name)
    if ($parts.Count -lt 1) {
        throw "Missing provider package parts for: $ZipPath"
    }
    Write-Host "Assembling $name from $($parts.Count) parts..."
    $out = [System.IO.File]::Create($ZipPath)
    try {
        foreach ($p in $parts) {
            $bytes = [System.IO.File]::ReadAllBytes($p.FullName)
            $out.Write($bytes, 0, $bytes.Length)
        }
    }
    finally {
        $out.Close()
    }
}

function Ensure-TfMirror {
    if (-not (Test-Path $MirrorRoot)) {
        throw "Provider mirror missing: $MirrorRoot (re-clone repo / pull latest)"
    }

    $awsDir = Join-Path $MirrorRoot "registry.terraform.io\hashicorp\aws"
    if (Test-Path $awsDir) {
        Get-ChildItem -Path $awsDir -Filter "terraform-provider-aws_*_windows_amd64.zip.part.00" -File | ForEach-Object {
            $zipName = $_.Name -replace '\.part\.00$', ''
            Join-ZipParts -ZipPath (Join-Path $awsDir $zipName)
        }
    }

    $rcPath = Join-Path $ScriptDir "terraform.rc"
    $mirrorPosix = ($MirrorRoot -replace '\\', '/')
    @"
# Generated by ensure-tf-mirror.ps1 - use local Windows provider mirror (no HashiCorp download)
provider_installation {
  filesystem_mirror {
    path    = "$mirrorPosix"
    include = ["registry.terraform.io/*/*"]
  }
  direct {
    exclude = ["registry.terraform.io/*/*"]
  }
}
"@ | Set-Content -Path $rcPath -Encoding ASCII

    $env:TF_CLI_CONFIG_FILE = $rcPath
    Write-Host "TF_CLI_CONFIG_FILE=$rcPath"
    Write-Host "Using offline provider mirror: $MirrorRoot"
}

Ensure-TfMirror
